export type LanguageCode = 'en' | 'hi'

type LanguageTools = {
  language: LanguageCode
  languageName: string
  setLanguage: (language: LanguageCode) => void
  t: (text: string) => string
}

export const LanguageContext = createContext<LanguageTools | null>(null)

export function useLanguage() {
  const tools = useContext(LanguageContext)
  if (!tools) throw new Error('useLanguage must be used inside LanguageProvider')
  return tools
}
